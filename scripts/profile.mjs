export const ORG = 'bobuk-io';
export const SITE = 'https://bobuk.io/';
const ASSETS = `https://raw.githubusercontent.com/${ORG}/.github/main/profile/assets/`;
const html = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const repoLink = name => `https://github.com/${ORG}/${encodeURIComponent(name)}`;

// Fail closed. Never infer visibility from missing fields, a local checkout,
// an app catalog, or the current user's access to a repository.
export function publicRepositories(repositories) {
  if (!Array.isArray(repositories)) throw new Error('GitHub returned a non-array repository list');
  return repositories.filter(repo =>
    repo && repo.private === false && repo.visibility === 'public' &&
    repo.owner?.login === ORG && typeof repo.name === 'string' &&
    /^[A-Za-z0-9_.-]+$/.test(repo.name) && repo.full_name === `${ORG}/${repo.name}`
  );
}

export function buildProfile(repositories, catalog) {
  const visible = publicRepositories(repositories);
  const active = new Map(visible.filter(repo => !repo.archived).map(repo => [repo.name, repo]));
  const apps = catalog.apps.filter(app => active.has(app.repo));
  const infrastructure = catalog.infrastructure.filter(item => active.has(item.repo));
  const used = new Set([...apps, ...infrastructure].map(item => item.repo));
  const other = visible.filter(repo => repo.name !== '.github' && !used.has(repo.name))
    .sort((a, b) => a.name.localeCompare(b.name));
  const assets = ['banner-light.svg', 'banner-dark.svg'];
  const parts = [
    '<!-- Generated by npm run prepare:profile. Edit design/catalog.json or scripts/profile.mjs. -->',
    `<a href="${SITE}">\n  <picture>\n    <source media="(prefers-color-scheme: dark)" srcset="${ASSETS}banner-dark.svg">\n    <img alt="bobuk.io — Less noise. More of your own work." src="${ASSETS}banner-light.svg" width="100%">\n  </picture>\n</a>`,
    'Small native macOS tools that solve a specific problem and respect your time.\nPublic source code, focused apps, and a place to ask for help.',
    `[Explore the apps, installation guides and support →](${SITE})`,
  ];
  if (apps.length) {
    parts.push('### Apps');
    const rows = apps.map(app => {
      if (!/^[a-z0-9-]+-icon\.png$/.test(app.icon) || !/^[a-z0-9-]+$/.test(app.slug)) {
        throw new Error('Unsafe app asset or slug');
      }
      if (app.cask && !/^[a-z0-9-]+$/.test(app.cask)) throw new Error('Unsafe cask');
      assets.push(app.icon);
      const appUrl = app.sourcePreview ? repoLink(app.repo) : `${SITE}apps/${app.slug}/`;
      const install = app.sourcePreview
        ? `<a href="${repoLink(app.repo)}#install-from-source">Build from source →</a> · No binary release yet.`
        : app.cask && active.has('homebrew-tap')
          ? `<code>brew install --cask bobuk-io/tap/${app.cask}</code>`
          : `<a href="${appUrl}">Install →</a>`;
      return `  <tr>\n    <td width="88" align="center"><a href="${appUrl}"><img src="${ASSETS}${app.icon}" width="64" alt="${html(app.name)} icon"></a></td>\n    <td>\n      <b><a href="${repoLink(app.repo)}">${html(app.name)}</a></b> · <sub>${html(app.category)}</sub><br>\n      <b>${html(app.tagline)}</b> ${html(app.description)}<br>\n      ${install}\n    </td>\n  </tr>`;
    });
    parts.push(`<table>\n${rows.join('\n')}\n</table>`);
  }
  parts.push('### How we build',
    '- **One thing, done well.** Not an everything app — a tool that fits into an ordinary day.\n- **The code is no secret.** Read how it works, open an issue, suggest a change.\n- **Somewhere to ask.** Find app information and support on [bobuk.io](https://bobuk.io/).');
  if (infrastructure.length) {
    parts.push('### Under the hood', infrastructure.map(item =>
      `<a href="${repoLink(item.repo)}"><code>${html(item.repo)}</code></a> — ${html(item.description)}`
    ).join(' ·\n'));
  }
  if (other.length) {
    parts.push('### More public repositories', '<ul>\n' + other.map(repo =>
      `  <li><a href="${repoLink(repo.name)}">${html(repo.name)}</a>${repo.archived ? ' (archived)' : ''}${repo.description ? ` — ${html(repo.description)}` : ''}</li>`
    ).join('\n') + '\n</ul>');
  }
  parts.push(`<sub><a href="${SITE}">English</a> · <a href="${SITE}ru/">Русский</a> · <a href="${SITE}uk/">Українська</a></sub>`);
  return { readme: parts.join('\n\n') + '\n', assets: [...new Set(assets)] };
}
